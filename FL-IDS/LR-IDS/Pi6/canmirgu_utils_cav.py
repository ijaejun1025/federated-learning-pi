#!/usr/bin/env python
# coding: utf-8

"""CAN-MIRGU Dataset loader — Pi6 (real, moving-vehicle CAN attacks, 2024).

The dataset's official UCI Machine Learning Repository file
(https://archive.ics.uci.edu/static/public/1035/can-mirgu.zip, the
"Download" button's real target) is confirmed corrupted as hosted -- two
independent HTTP clients (curl and PowerShell's Invoke-WebRequest)
downloaded byte-identical, unparseable zip data from it (no valid local
file header anywhere in the file). This loader still tries that URL first
in case UCI fixes it, but the real working source turned out to be the
dataset author's own Google Drive folder linked from
https://github.com/sampathrajapaksha/CAN-MIRGU's readme -- that folder *is*
the full dataset (not the small "Sample dataset" also in that repo), just
split by Google's own folder-download zipping into
``CAN-MIRGU-<timestamp>-1-00{1,2,3}.zip``. Since Drive folder downloads
aren't reliably scriptable (the zip is generated by an internal web-app
call, not a stable URL), auto-download here targets three direct Drive
file links instead: each of those three parts uploaded to this project's
own Drive, downloaded with ``common_cav.download_from_google_drive``
(which handles Google's large-file virus-scan interstitial page, very
likely to trigger here given these files are 300-400MB each). If every automatic path fails,
download manually via either URL above and place the extracted files
anywhere under ``CAN-MIRGU/`` next to this file.

Structure and format (confirmed against the real, full downloaded
dataset -- 48 candump ``.log`` files, ~5.5GB uncompressed): a top-level
``Benign/`` folder with ``Day_1`` .. ``Day_6`` subfolders, and an
``Attack/`` folder containing ``Real_attacks/``, ``Masquerade_attacks/``,
and ``Suspension_attacks/`` subfolders. Every line is a candump frame
followed by that frame's own label: ``(timestamp) can0 ID#HEXDATA 0|1``.

Labels: the per-frame label at the end of each line is used. An attack
capture is mostly normal traffic -- e.g. only 10,936 of
Break_warning_attack's 588,592 frames are injected (327 of 233,555 in
Wiper_warning_attack) -- so labeling whole attack files as attack, as an
earlier version did, marked ~99% normal frames as attacks. On every attack
capture that has an entry in ``Attack/Attacks_metadata.json``, the frames
labeled 1 are exactly the frames inside the injection interval with the
injected CAN ID and data pattern. Every benign frame is labeled 0.

Captures used: ``Benign/`` and ``Attack/Real_attacks/`` only.
``Masquerade_attacks/`` files are real-attack captures with the genuine
frames removed (same injected frames), so they would only duplicate them.
``Suspension_attacks/`` files label 27-43% of all frames, across many CAN
IDs, as attack; those frames match normal traffic in payload and timing,
because the attack is the *absence* of one ECU's messages, which a model
that classifies single frames cannot see.

Split: benign captures by recording day; attack captures as in ROAD (Pi5),
so every attack type in test was also seen in training.
- Benign: several files are consecutive parts of one recording, cut every
  10M lines (day1 file1->2->3, day1 file4->5, day2 file1->2 follow each other
  with no gap), so a per-file split would put the two halves of one drive in
  train and test. Whole days go to one side instead: ``BENIGN_TEST_DAYS``
  (Day_2, Day_4, Day_6, ~38% of the benign frames) are test, the rest train.
- Attacks recorded more than once (``Gear_shifter_attack_1/2``,
  ``Min_speedometer_attack_1/2/3``, ``Multiple_attacks_1/2``): recording 1
  is test, the others train. Attack captures are independent recordings: no
  16-frame sequence of one occurs in any other capture.
- Attacks recorded once: 10 contiguous time blocks, blocks 2, 5 and 8 test
  (see ``common_cav.time_block_layout``). Every such capture then has
  attack frames on both sides except Fuzzing_valid_IDs_DoS (its injections
  fall in train blocks only); DoS_attack and Fuzzing_valid_IDs cover that
  attack in test.
The benign train captures feed the ID period table.
"""

import glob
import os
import re
import urllib.request
import zipfile

import common_cav

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
CANMIRGU_DIR = os.path.join(BASE_DIR, "CAN-MIRGU")
# Renamed whenever the rows, labels or features change: a cache is found by
# this key alone, so an old cache would otherwise keep being used.
DATASET_KEY = "canmirgu_h12r_s1_fs"
BENIGN_TEST_DAYS = ("Day_2", "Day_4", "Day_6")
REPEATED_ATTACK_RE = re.compile(r"_(\d+)$")  # Gear_shifter_attack_1, ...
TEST_REPEAT = "1"
UCI_ZIP_URL = "https://archive.ics.uci.edu/static/public/1035/can-mirgu.zip"
SOURCE_URLS = (
    "https://archive.ics.uci.edu/dataset/1035/can-mirgu",
    "https://github.com/sampathrajapaksha/CAN-MIRGU",
)
# The GitHub readme's Google Drive folder, split into 3 parts by Google's
# own folder-download zipping, each re-uploaded to this project's own
# Drive (see module docstring) so it can be downloaded by direct file ID.
GOOGLE_DRIVE_FILE_IDS = (
    "1QZZLbA5fkjc_DdBfSvDYk1Zm03ysZA2V",  # CAN-MIRGU-...-1-001.zip
    "1EkPUOtpBUtyZpP811QS_bA3htbFPHuff",  # CAN-MIRGU-...-1-002.zip
    "1xgyNExQi02eY38UOCzkH040INVshCw6u",  # CAN-MIRGU-...-1-003.zip
)

BENIGN_FOLDER = "Benign"
REAL_ATTACK_FOLDER = "Real_attacks"
EXCLUDED_ATTACK_FOLDERS = ("Masquerade_attacks", "Suspension_attacks")

# The used captures hold ~118M frames. Every frame is read (the time features
# need all of them); rows are then sampled as for every dataset.
SAMPLING = common_cav.Sampling()

reshape_for_cnn = common_cav.reshape_for_cnn


def _find_files():
    return sorted(glob.glob(os.path.join(CANMIRGU_DIR, "**", "*.log"), recursive=True))


def _extract_all_nested_zips() -> None:
    """UCI's archive is a zip inside a zip, and a few individual captures
    are further zipped on their own; keep extracting until none remain.
    """
    while True:
        nested = glob.glob(os.path.join(CANMIRGU_DIR, "**", "*.zip"), recursive=True)
        if not nested:
            return
        for zip_path in nested:
            with zipfile.ZipFile(zip_path, "r") as zf:
                zf.extractall(os.path.dirname(zip_path))
            os.remove(zip_path)


def _download_canmirgu_from_uci() -> None:
    os.makedirs(CANMIRGU_DIR, exist_ok=True)
    zip_path = os.path.join(CANMIRGU_DIR, "canmirgu_download.zip")
    urllib.request.urlretrieve(UCI_ZIP_URL, zip_path)
    with zipfile.ZipFile(zip_path, "r") as zf:
        zf.extractall(CANMIRGU_DIR)
    os.remove(zip_path)
    _extract_all_nested_zips()


def _download_canmirgu_from_drive_mirror() -> None:
    os.makedirs(CANMIRGU_DIR, exist_ok=True)
    for i, file_id in enumerate(GOOGLE_DRIVE_FILE_IDS, start=1):
        zip_path = os.path.join(CANMIRGU_DIR, f"canmirgu_part_{i}.zip")
        common_cav.download_from_google_drive(file_id, zip_path)
        with zipfile.ZipFile(zip_path, "r") as zf:
            zf.extractall(CANMIRGU_DIR)
        os.remove(zip_path)


def _ensure_raw_files() -> list:
    files = _find_files()
    if files:
        return files

    errors = []
    for source_name, download_fn in (
        ("UCI", _download_canmirgu_from_uci),
        ("Google Drive mirror", _download_canmirgu_from_drive_mirror),
    ):
        try:
            download_fn()
        except Exception as error:
            errors.append(f"{source_name}: {error}")
            continue
        files = _find_files()
        if files:
            return files

    raise FileNotFoundError(
        f"No CAN-MIRGU capture files found under '{CANMIRGU_DIR}', and "
        f"every automatic download attempt failed ({'; '.join(errors)}). "
        f"Download manually from {' or '.join(SOURCE_URLS)} and place the "
        f"extracted files under '{CANMIRGU_DIR}'."
    )


def _capture_folders(path: str) -> list:
    return os.path.relpath(path, CANMIRGU_DIR).split(os.sep)[:-1]


def _capture_frames(path: str) -> common_cav.Frames:
    """Every frame with its own trailing 0/1 label (a frame without one raises)."""
    ts, can_id, payload_hex, label = common_cav.read_candump_log(path, with_label=True)
    dlc, data = common_cav.hex_payloads(payload_hex)
    return common_cav.make_frames(ts, can_id, dlc, data, label)


def _used_captures(files: list):
    """Split the captures into (benign, real_attack); masquerade and
    suspension captures are left out (see module docstring)."""
    benign, real_attack = [], []
    for path in files:
        folders = _capture_folders(path)
        if any(name in folders for name in EXCLUDED_ATTACK_FOLDERS):
            continue
        if BENIGN_FOLDER in folders:
            benign.append(path)
        elif REAL_ATTACK_FOLDER in folders:
            real_attack.append(path)
        else:
            raise ValueError(f"Unexpected CAN-MIRGU capture location: {os.path.relpath(path, CANMIRGU_DIR)}")
    return benign, real_attack


def _attack_splits(attack: list) -> dict:
    """Split of each attack capture: repeated attacks by recording, the
    others by time blocks (see module docstring)."""
    groups = {}
    for path in attack:
        name = os.path.splitext(os.path.basename(path))[0]
        match = REPEATED_ATTACK_RE.search(name)
        groups.setdefault(name[:match.start()] if match else name, []).append((path, match))
    splits = {}
    for stem, members in groups.items():
        if len(members) == 1:
            splits[members[0][0]] = "blocks"
            continue
        repeats = {match.group(1) if match else None for _, match in members}
        if TEST_REPEAT not in repeats or None in repeats:
            raise ValueError(f"repeated attack {stem!r} has recordings {sorted(map(str, repeats))}, "
                             f"expected numbered ones including {TEST_REPEAT}")
        for path, match in members:
            splits[path] = "test" if match.group(1) == TEST_REPEAT else "train"
    return splits


def _captures() -> list:
    """Benign captures split by recording day, attack captures by recording
    or time blocks (see module docstring)."""
    benign, attack = _used_captures(_ensure_raw_files())
    benign_test = {p for p in benign if any(day in _capture_folders(p) for day in BENIGN_TEST_DAYS)}
    days = {f for p in benign for f in _capture_folders(p) if f.startswith("Day_")}
    if not set(BENIGN_TEST_DAYS) <= days or not benign_test or len(benign_test) == len(benign):
        raise ValueError(f"benign day folders {sorted(days)} do not fit BENIGN_TEST_DAYS {BENIGN_TEST_DAYS}")
    splits = {p: "test" if p in benign_test else "train" for p in benign}
    splits.update(_attack_splits(attack))
    return [
        common_cav.Capture(
            os.path.basename(path), lambda path=path: _capture_frames(path),
            split=splits[path], attack_free=path in benign,
        )
        for path in benign + attack
    ]


def get_global_train_test_split(test_size: float = 0.33, random_state: int = 41):
    cached = common_cav.find_any_cached_split(DATASET_KEY, BASE_DIR, test_size, random_state)
    if cached is not None:
        # A split_cache/*.npz already exists -- use it without ever
        # touching the (5.5GB) raw dataset, e.g. on a disk-constrained
        # device that only has the cache copied onto it.
        return cached

    files = _ensure_raw_files()
    source_version = common_cav.directory_signature(files)
    split = common_cav.build_feature_split(_captures(), SAMPLING, random_state)
    return common_cav.cache_split(
        DATASET_KEY, BASE_DIR, split, source_version, test_size, random_state,
        common_cav.period_table_arrays(split.tables),
    )


def get_client_data(test_size: float = 0.33, random_state: int = 41, local_val_size: float = 0.2):
    """The client's training rows (already sampled to their final size when
    the cache was built), split into local train / validation."""
    cached = common_cav.load_cached(DATASET_KEY, BASE_DIR, ("x_train", "y_train"), test_size, random_state)
    if cached is None:
        x_train, _, y_train, _ = get_global_train_test_split(test_size, random_state)
    else:
        x_train, y_train = cached
    return common_cav.local_train_val_split(x_train, y_train, local_val_size, random_state)


def get_test_split(test_size: float = 0.33, random_state: int = 41):
    _, x_test, _, y_test = get_global_train_test_split(test_size, random_state)
    return x_test, y_test
